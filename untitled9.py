def _real_generate(prompt: str, api_key: str, image_bytes: bytes | None = None,
                    image_mime: str = "image/jpeg", model: str | None = None,
                    retries: int = 3) -> dict:
    """Calls the Gemini generateContent endpoint. Returns dict with
    text / refused / finish_reason / raw."""
    key = _require_api_key(api_key)
    use_model = model or GENERATION_MODEL
    url = f"{API_BASE}/models/{use_model}:generateContent?key={key}"

    parts = [{"text": prompt}]
    if image_bytes is not None:
        import base64
        parts.append({
            "inline_data": {
                "mime_type": image_mime,
                "data": base64.b64encode(image_bytes).decode("utf-8"),
            }
        })
    payload = {"contents": [{"parts": parts}]}

    last_err = None
    for attempt in range(retries):
        try:
            resp = requests.post(url, json=payload, timeout=30)
            resp.raise_for_status()
            return _parse_generate_response(resp.json())
        except requests.exceptions.RequestException as e:
            last_err = e
            time.sleep(min(2 ** attempt, 8))
    raise GeminiError(f"generate() failed after {retries} attempts: {last_err}")


def _parse_generate_response(data: dict) -> dict:
    candidates = data.get("candidates", [])
    if not candidates:
        return {
            "text": "",
            "refused": True,
            "finish_reason": data.get("promptFeedback", {}).get("blockReason", "PROMPT_BLOCKED"),
            "raw": data,
        }
    candidate = candidates[0]
    finish_reason = candidate.get("finishReason", "")
    parts = candidate.get("content", {}).get("parts", [])
    text = "".join(p.get("text", "") for p in parts)
    refused = finish_reason in ("SAFETY", "RECITATION", "BLOCKLIST", "PROHIBITED_CONTENT")
    return {"text": text, "refused": refused, "finish_reason": finish_reason, "raw": data}


def _real_embed(text: str, api_key: str, retries: int = 3) -> list[float]:
    key = _require_api_key(api_key)
    url = f"{API_BASE}/models/{EMBEDDING_MODEL}:embedContent?key={key}"
    payload = {"content": {"parts": [{"text": text}]}}

    last_err = None
    for attempt in range(retries):
        try:
            resp = requests.post(url, json=payload, timeout=30)
            resp.raise_for_status()
            return resp.json()["embedding"]["values"]
        except requests.exceptions.RequestException as e:
            last_err = e
            time.sleep(min(2 ** attempt, 8))
    raise GeminiError(f"embed() failed after {retries} attempts: {last_err}")

